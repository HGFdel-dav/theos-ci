#!/bin/sh
set -eu
cd "$(dirname "$0")"
if [ "${GITHUB_ACTIONS:-}" != true ] || [ "${RUNNER_OS:-}" != macOS ]; then
    echo 'Build blocked: iOS machine code is generated by approved GitHub CI only.' >&2
    exit 2
fi
: "${THEOS:?GitHub CI must configure THEOS}"
test -d "$THEOS/sdks/iPhoneOS15.5.sdk"
make clean THEOS_PACKAGE_SCHEME=roothide
make package FINALPACKAGE=1 THEOS_PACKAGE_SCHEME=roothide
